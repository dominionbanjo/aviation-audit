import { pgTable, varchar, timestamp, text, uniqueIndex, uuid, index } from "drizzle-orm/pg-core";
import { relations, sql } from "drizzle-orm";
import { users } from "./users";
import { auditTemplates } from "./audit-templates";
import { auditQuestions } from "./audit-templates";

// ─── Submitted Audits ────────────────────────────────────────────────────────
export const audits = pgTable("audits", {
  id: uuid("id").primaryKey().defaultRandom(),
  refNo: varchar("ref_no").notNull().unique(), // e.g., AD-0001 — generated by backend before insert
  templateId: uuid("template_id")
    .notNull()
    .references(() => auditTemplates.id, { onDelete: "restrict" }),
  auditorId: varchar("auditor_id")
    .notNull()
    .references(() => users.id, { onDelete: "restrict" }),
  location: varchar("location").notNull(),
  date: timestamp("date", { withTimezone: true }).notNull(),
  status: varchar("status").notNull().default("in-progress"), // 'in-progress' | 'completed'
  startedAt: timestamp("started_at", { withTimezone: true }).defaultNow().notNull(),
  completedAt: timestamp("completed_at", { withTimezone: true }),
}, (table) => {
  return {
    startedAtIdx: index("idx_audits_started_at").on(table.startedAt),
    statusIdx: index("idx_audits_status").on(table.status),
    templateIdIdx: index("idx_audits_template_id").on(table.templateId),
  };
});


// ─── Audit Responses ─────────────────────────────────────────────────────────
export const auditResponses = pgTable("audit_responses", {
  id: uuid("id").primaryKey().defaultRandom(),
  auditId: uuid("audit_id")
    .notNull()
    .references(() => audits.id, { onDelete: "cascade" }),
  questionId: uuid("question_id")
    .notNull()
    .references(() => auditQuestions.id, { onDelete: "restrict" }),
  responseValue: varchar("response_value"), // 'SAT' | 'UNSAT' | 'N/A'
  comment: text("comment"),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),

  // Findings & CAR Tracking Columns
  rootCause: text("root_cause"),
  correctiveAction: text("corrective_action"),
  responsiblePerson: varchar("responsible_person"),
  deadline: timestamp("deadline", { withTimezone: true }),
  findingStatus: varchar("finding_status", { length: 20 }).default("open").notNull(), // 'open' | 'under-review' | 'closed'
  resolvedAt: timestamp("resolved_at", { withTimezone: true }),
}, (table) => {
  return {
    auditQuestionIdx: uniqueIndex("audit_question_idx").on(table.auditId, table.questionId),
    auditIdIdx: index("idx_responses_audit_id").on(table.auditId),
    questionIdIdx: index("idx_responses_question_id").on(table.questionId),
    valueIdx: index("idx_responses_value").on(table.responseValue),
  };
});


// ─── Relations ─────────────────────────────────────────────────────────────────
export const auditsRelations = relations(audits, ({ one, many }) => ({
  template: one(auditTemplates, {
    fields: [audits.templateId],
    references: [auditTemplates.id],
  }),
  auditor: one(users, {
    fields: [audits.auditorId],
    references: [users.id],
  }),
  responses: many(auditResponses),
}));

export const auditResponsesRelations = relations(auditResponses, ({ one }) => ({
  audit: one(audits, {
    fields: [auditResponses.auditId],
    references: [audits.id],
  }),
  question: one(auditQuestions, {
    fields: [auditResponses.questionId],
    references: [auditQuestions.id],
  }),
}));


// ─── Types ────────────────────────────────────────────────────────────────────
export type Audit = typeof audits.$inferSelect;
export type InsertAudit = typeof audits.$inferInsert;

export type AuditResponse = typeof auditResponses.$inferSelect;
export type InsertAuditResponse = typeof auditResponses.$inferInsert;
